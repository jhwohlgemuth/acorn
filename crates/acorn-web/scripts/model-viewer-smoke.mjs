import assert from "node:assert/strict";
import { mkdir, readFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";
import { startModelViewer } from "./model-viewer.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = resolve(root, "../../output/designs/cesium-objects");
const server = await startModelViewer(0);
const origin = `http://127.0.0.1:${server.address().port}`;
let browser;
try {
    browser = await chromium.launch();
    const page = await browser.newPage({ viewport: { width: 1320, height: 900 } });
    const errors = [];
    const external = [];
    page.on("pageerror", (error) => errors.push(String(error)));
    await page.route("**/*", (route) => {
        if (route.request().url().startsWith(`${origin}/`)) void route.continue();
        else { external.push(route.request().url()); void route.abort(); }
    });
    const ready = (label) => page.waitForFunction((name) => document.getElementById("status").textContent === `${name} ready`, label);
    const render = () => page.evaluate(() => new Promise((done) => requestAnimationFrame(() => requestAnimationFrame(done))));
    await page.goto(origin);
    await ready("Supercomputer");
    assert.equal(await page.locator("#asset").inputValue(), "research/supercomputer");
    assert.equal(await page.locator("#download").getAttribute("href"), "/models/research/supercomputer.glb");
    await render();
    await mkdir(output, { recursive: true });
    await page.screenshot({ path: `${output}/model-viewer-desktop.png` });
    const canvas = page.locator("canvas");
    const before = await canvas.screenshot();
    const box = await canvas.boundingBox();
    await page.mouse.move(box.x + box.width * 0.4, box.y + box.height * 0.4);
    await page.mouse.down();
    await page.mouse.move(box.x + box.width * 0.6, box.y + box.height * 0.5, { steps: 12 });
    await page.mouse.up();
    await render();
    assert.notDeepEqual(await canvas.screenshot(), before, "Dragging must orbit the model");
    assert.equal(await page.locator("#view-name").textContent(), "Custom view");
    const orbited = await canvas.screenshot();
    await page.mouse.wheel(0, -180);
    await render();
    assert.notDeepEqual(await canvas.screenshot(), orbited, "Wheel must zoom the model");
    await page.locator("#viewport").focus();
    await page.keyboard.press("r");
    assert.equal(await page.locator("#view-name").textContent(), "Perspective");
    await page.keyboard.press("ArrowLeft");
    assert.equal(await page.locator("#view-name").textContent(), "Custom view");
    await page.getByRole("button", { name: "Front", exact: true }).click();
    assert.equal(await page.locator("#view-name").textContent(), "Front");
    await page.getByRole("button", { name: "Reset view", exact: true }).click();
    const catalog = JSON.parse(await readFile(resolve(root, "assets/models/catalog.json"), "utf8"));
    const next = page.getByRole("button", { name: "Next model", exact: true });
    const previous = page.getByRole("button", { name: "Previous model", exact: true });
    const options = await page.locator("#asset option").evaluateAll((items) => items.map((item) => ({ id: item.value, label: item.label })));
    const nextAsset = options[options.findIndex((item) => item.id === "research/supercomputer") + 1];
    await next.click();
    await ready(nextAsset.label);
    assert.equal(await page.locator("#asset").inputValue(), nextAsset.id);
    await previous.click();
    await ready("Supercomputer");
    const download = await page.request.get(`${origin}/models/research/supercomputer.glb`);
    assert.equal(download.status(), 200);
    assert.equal((await download.body()).length, catalog.assets.find((asset) => asset.id === "research/supercomputer").bytes);
    assert.equal((await page.request.get(`${origin}/models/research/supercomputer.model.json`)).status(), 404);
    assert.equal((await page.request.get(`${origin}/models/%2e%2e%2f%2e%2e%2fpackage.json`)).status(), 404);
    await page.locator("#categories").selectOption("drone");
    assert.equal(await page.locator("#asset option").count(), catalog.assets.filter((asset) => asset.category === "drone").length);
    assert.deepEqual(await page.locator("#asset optgroup").evaluateAll((groups) => groups.map((group) => group.label)), ["Drones"]);
    await next.click();
    await ready(options[0].label);
    assert.equal(await previous.isDisabled(), true);
    await page.locator("#asset-search").fill("matrice 350");
    assert.equal(await page.locator("#asset option").count(), 1);
    await page.locator("#asset").selectOption("drone/dji-matrice-350-rtk");
    await ready("DJI Matrice 350 RTK");
    assert.equal(await next.isDisabled(), true);
    assert.equal(await previous.isDisabled(), true);
    assert.equal(await page.locator("#download").getAttribute("href"), "/models/drones/dji-matrice-350-rtk.glb");
    assert.equal((await page.request.get(`${origin}/models/drones/dji-matrice-350-rtk.glb`)).status(), 200);
    assert.equal((await page.request.get(`${origin}/models/drone/dji-matrice-350-rtk.glb`)).status(), 404);
    await page.locator("#asset-search").fill("no-such-asset");
    assert.equal(await page.locator("#empty-results").isVisible(), true);
    assert.equal(await page.locator("#asset").isDisabled(), true);
    assert.equal(await next.isDisabled(), true);
    assert.equal(await previous.isDisabled(), true);
    await page.getByRole("button", { name: "Clear filters" }).click();
    assert.equal(await page.locator("#asset option").count(), catalog.assets.length);
    assert.deepEqual(await page.locator("#asset optgroup").evaluateAll((groups) => groups.map((group) => group.label)), ["Drones", "Landmarks", "Research"]);
    assert.equal(await page.locator('#categories option[value="other"]').count(), 0);
    assert.equal((await page.request.get(`${origin}/models/other/player-pawn.glb`)).status(), 404);
    await page.locator("#categories").selectOption("drone");
    await page.locator("#asset-search").fill("landing pad");
    assert.equal(await page.locator("#asset option").count(), 1);
    await page.locator("#asset").selectOption("drone/landing-pad");
    await ready("Landing Pad");
    assert.equal(await page.locator("#download").getAttribute("href"), "/models/drones/landing-pad.glb");
    assert.equal((await page.request.get(`${origin}/models/drones/landing-pad.glb`)).status(), 200);
    await page.getByRole("button", { name: "Clear filters" }).click();
    const firstLandmark = options.findIndex((item) => item.id.startsWith("landmarks/"));
    await page.locator("#asset").selectOption(options[firstLandmark - 1].id);
    await ready(options[firstLandmark - 1].label);
    await next.click();
    await ready(options[firstLandmark].label);
    await previous.click();
    await ready(options[firstLandmark - 1].label);
    await page.locator("#asset").selectOption(options.at(-1).id);
    await ready(options.at(-1).label);
    assert.equal(await next.isDisabled(), true);
    await page.locator("#theme-toggle").click();
    assert.equal(await page.locator("body").getAttribute("data-theme"), "light");
    await page.reload();
    await ready("Supercomputer");
    assert.equal(await page.locator("body").getAttribute("data-theme"), "light");
    await page.screenshot({ path: `${output}/model-viewer-light.png` });
    await page.locator("#theme-toggle").click();
    assert.equal(await page.locator(".sidebar, .mobile-bar, h1, .page-header, #nav-toggle").count(), 0);
    assert.equal(await page.locator("main").evaluate((node) => getComputedStyle(node).marginLeft), "0px");
    assert.equal(await page.locator(".toolbar button").first().evaluate((node) => getComputedStyle(node).boxShadow), "none");
    assert.equal(await page.locator("#theme-toggle").evaluate((node) => getComputedStyle(node).boxShadow), "none");
    const original = catalog.assets.find((asset) => asset.id === "research/supercomputer");
    await page.route("**/models/catalog.json", (route) => route.fulfill({ json: { version: 1, assets: [original,
        { ...original, id: "research/alternate", label: "Alternate specimen" },
        { ...original, id: "research/missing", label: "Missing specimen", file: "research/missing.glb" },
    ] } }));
    await page.reload();
    await ready("Supercomputer");
    await page.locator("#asset").selectOption("research/alternate");
    await ready("Alternate specimen");
    assert.equal(await page.locator("#model-name").textContent(), "Alternate specimen");
    await next.click();
    await page.waitForFunction(() => document.getElementById("status").dataset.error === "true");
    assert.equal(await page.locator("#asset").inputValue(), "research/alternate");
    assert.equal(await page.locator("#viewport").getAttribute("data-asset"), "research/alternate");
    assert.equal(await next.isEnabled(), true);
    assert.equal(await previous.isDisabled(), true);
    await page.locator("#asset").selectOption("research/supercomputer");
    await ready("Supercomputer");
    await page.unroute("**/models/catalog.json");
    await page.reload();
    await ready("Supercomputer");
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.locator("#categories").isVisible(), true);
    assert.equal(await page.locator("#theme-toggle").isVisible(), true);
    assert.equal(await page.locator(".sidebar, .mobile-bar, h1, #nav-toggle").count(), 0);
    assert.equal(await next.isVisible(), true);
    assert.equal(await previous.isVisible(), true);
    await render();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Mobile layout overflows");
    await page.screenshot({ path: `${output}/model-viewer-mobile.png`, fullPage: true });
    await page.route("**/models/catalog.json", (route) => route.fulfill({ json: { version: 1, assets: [] } }));
    await page.reload();
    await page.waitForFunction(() => document.getElementById("status").textContent.includes("No models yet"));
    assert.equal(await page.locator("#asset").isDisabled(), true);
    assert.deepEqual(errors, []);
    assert.deepEqual(external, []);
    console.log("Model viewer passed: real GLB, orbit, zoom, keyboard/reset, picker replacement, failed-load recovery, download, scoped serving, mobile, search/category filters, theme persistence, single-page layout without sidebar/title, renamed drones URLs, empty collection, no external requests.");
} finally {
    if (browser) await browser.close();
    await new Promise((done) => server.close(done));
}
