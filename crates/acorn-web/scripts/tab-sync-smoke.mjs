async function assertPidUnderlineColors(page) {
    const colors = await page.evaluate(() => {
        const workspace = document.querySelector(".workspace");
        const originalTheme = workspace.getAttribute("data-theme");
        const marks = Array.from(document.querySelectorAll(".cm-discovered-pid[data-pid]"));
        const badges = Array.from(document.querySelectorAll(".pid-badge[data-pid]"));
        try {
            return ["dark", "light"].map(theme => {
                workspace.setAttribute("data-theme", theme);
                return marks.map(mark => ({
                    kind: mark.dataset.pid,
                    underline: getComputedStyle(mark).textDecorationColor,
                    tag: getComputedStyle(badges.find(badge => badge.dataset.pid === mark.dataset.pid)).color,
                }));
            });
        } finally {
            if (originalTheme === null) workspace.removeAttribute("data-theme");
            else workspace.setAttribute("data-theme", originalTheme);
        }
    });
    assert.ok(new Set(colors[0].map(color => color.kind)).size > 1, "the example discovers multiple PID types");
    for (const theme of colors) {
        assert.ok(new Set(theme.map(color => color.underline)).size > 1, "PID types use distinct underline colors");
        for (const color of theme) assert.equal(color.underline, color.tag, `${color.kind} underline matches its tag`);
    }
}
