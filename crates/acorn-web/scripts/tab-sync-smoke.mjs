import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createServer } from "node:http";
import { extname, resolve, sep } from "node:path";
import { chromium } from "playwright";

const root = resolve(process.argv[2]);
const prefix = `/${(process.argv[3] ?? "").replace(/^\/+|\/+$/g, "")}`.replace(/\/$/, "");
const types = { ".css": "text/css", ".html": "text/html", ".js": "text/javascript", ".json": "application/json", ".svg": "image/svg+xml", ".wasm": "application/wasm" };
const server = createServer(async (request, response) => {
    try {
        const path = decodeURIComponent(new URL(request.url, "http://localhost").pathname);
        assert.ok(path.startsWith(`${prefix}/`));
        const relative = path.slice(prefix.length);
        const file = resolve(root, `.${relative}`);
        assert.ok(file === root || file.startsWith(`${root}${sep}`));
        const candidate = relative === "/" ? `${root}/index.html` : file;
        const bytes = await readFile(candidate).catch(() => readFile(`${root}/index.html`));
        response.writeHead(200, { "Content-Type": types[extname(candidate)] ?? "text/html" });
        response.end(bytes);
    } catch {
        response.writeHead(404);
        response.end();
    }
});
await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
const browser = await chromium.launch();
try {
    const context = await browser.newContext();
    const page = await context.newPage();
    page.setDefaultTimeout(15000);
    await page.goto(`http://127.0.0.1:${server.address().port}${prefix}/`);
    await page.getByRole("button", { name: "Try Sample Data" }).click();
    await page.getByRole("heading", { name: "Portfolio", exact: true }).waitFor();
    await page.locator(".dashboard-settings > summary").click();
    const popupPromise = page.context().waitForEvent("page");
    await page.getByRole("link", { name: "Open dashboard in new tab" }).click();
    const dashboard = await popupPromise;
    await dashboard.getByRole("heading", { name: "Dashboard", exact: true }).waitFor();
    await dashboard.waitForFunction(() => Number(document.querySelector('.metric[data-tile-id="activities"] strong')?.textContent) > 0);
    assert.equal(await dashboard.locator("#workspace-navigation, .mobile-bar, .page-toolbar").count(), 0, "the dashboard tab contains no workspace navigation or toolbar");
    assert.equal(await dashboard.locator("main").evaluate(node => getComputedStyle(node).marginLeft), "0px", "the dashboard uses the full tab width");
    await page.locator('nav a[title="Settings"]').click();
    await page.getByRole("button", { name: "Delete all data" }).click();
    await dashboard.waitForFunction(() => document.querySelector('.metric[data-tile-id="activities"] strong')?.textContent === "0");
    await page.locator('nav a[title="Home"]').click();
    await page.getByRole("button", { name: "Try Sample Data" }).click();
    await dashboard.waitForFunction(() => Number(document.querySelector('.metric[data-tile-id="activities"] strong')?.textContent) > 0);
    await dashboard.close();
    await page.locator('nav a[title="Review"]').click();
    await page.locator(".code-editor:has(#content).cm-ready").waitFor();
    await page.locator("#content-editor").press("ControlOrMeta+End");
    await page.keyboard.insertText(" ");
    const source = await page.locator("#content").inputValue();
    const ordinary = await page.context().newPage();
    await ordinary.goto(page.url());
    await ordinary.locator("#content").waitFor({ state: "attached" });
    await ordinary.waitForFunction(text => document.getElementById("content")?.value === text, source);
    assert.equal(await page.locator("#content").inputValue(), source, "opening an ordinary tab preserves the active draft");
    await ordinary.close();
    const editorPromise = page.context().waitForEvent("page");
    await page.locator(".code-editor:has(#content)").getByRole("button", { name: "Open code editor in new tab" }).click();
    const editor = await editorPromise;
    await editor.locator("#content-editor").waitFor();
    assert.equal(await editor.locator("#workspace-navigation, .mobile-bar, .page-toolbar").count(), 0, "the code editor tab contains no workspace navigation or toolbar");
    await editor.getByRole("button", { name: "Find", exact: true }).waitFor();
    await editor.locator(".tool-settings").waitFor({ state: "attached" });
    await editor.locator(".results").waitFor({ state: "attached" });
    const popoutEditor = editor.locator(".code-editor:has(#content)");
    await popoutEditor.locator(".editor-run-action").waitFor();
    await editor.waitForFunction(() => document.querySelector(".code-editor:has(#content)")?.classList.contains("is-fullscreen"));
    const exitFullscreen = popoutEditor.getByRole("button", { name: "Exit full screen" });
    assert.equal(await exitFullscreen.isDisabled(), true, "the editor tab cannot exit full screen");
    await editor.locator("#content-editor").press("Escape");
    assert.equal(await popoutEditor.evaluate(node => node.classList.contains("is-fullscreen")), true, "Escape keeps the editor tab full screen");
    await editor.evaluate(() => window.acornEditors.toggleFullscreen("content"));
    assert.equal(await popoutEditor.evaluate(node => node.classList.contains("is-fullscreen")), true, "the full-screen API keeps the editor tab locked");
    await page.getByRole("link", { name: "Open code editor tab" }).waitFor();
    await page.locator(".review-modes button").filter({ hasText: "FAIR" }).click();
    await editor.waitForFunction(() => document.querySelector('.review-modes button[aria-pressed="true"]')?.textContent?.includes("FAIR"));
    assert.equal(await popoutEditor.evaluate(node => node.classList.contains("is-fullscreen")), true, "changing review modes keeps the editor full screen");
    assert.equal(await exitFullscreen.isDisabled(), true, "changing review modes keeps Exit full screen disabled");
    await page.locator(".review-modes button").filter({ hasText: "Metadata" }).click();
    await editor.waitForFunction(() => document.querySelector('.review-modes button[aria-pressed="true"]')?.textContent?.includes("Metadata"));
    assert.equal(await editor.locator("#content").inputValue(), source);
    await editor.locator("#content-editor").press("ControlOrMeta+End");
    await editor.keyboard.insertText(" ");
    await page.waitForFunction(text => document.getElementById("content")?.value === `${text} `, source);
    await page.getByRole("button", { name: "Use example" }).click();
    await editor.waitForFunction(() => document.getElementById("content")?.value.length > 20);
    const example = await editor.locator("#content").inputValue();
    await page.waitForFunction(text => document.getElementById("content")?.value === text, example);
    await popoutEditor.locator(".editor-run-action").click();
    await page.locator(".results .empty").waitFor({ state: "detached" });
    await page.locator(".editor-issue-nav:not([hidden])").waitFor({ state: "attached" });
    assert.equal(await page.locator("#content").inputValue(), await editor.locator("#content").inputValue());
    await editor.evaluate(() => { window.acornOperations.run = () => new Promise(() => {}); });
    await popoutEditor.locator(".editor-run-action").click();
    await editor.locator("#tool-run[disabled]").waitFor();
    await editor.close();
    await page.locator("#tool-run:not([disabled])").waitFor();
    await page.locator(".editor-popout-placeholder").waitFor({ state: "detached" });
    await page.locator(".code-editor:has(#content) .editor-toolbar").waitFor({ state: "visible" });
    console.log("Dashboard and code editor tabs synchronized.");
} finally {
    await browser.close();
    await new Promise(resolve => server.close(resolve));
}
